CATALOGUE_GEN = """#!/usr/bin/env python3
import glob, re
rows = []
for p in sorted(glob.glob("tools/*.sh")):
    purpose = next((m.group(1) for m in map(re.compile(r"# Purpose: (.*)").match, open(p)) if m), "-")
    rows.append(f"| `{p}` | {purpose} |\\n")
with open("docs/tools.md", "w") as f:
    f.write(f"# Tools\\n\\nGENERATED by scripts/catalogue.\\n\\n## Tools ({len(rows)})\\n\\n| Tool | Purpose |\\n"
            + "".join(rows))
with open("{log}", "a") as f:
    f.write("ran\\n")
"""
# the repo's path-closure generator (as scripts/ci/convergence_paths.py --write): the hand-written lines kept, the
# block between its BEGIN and END lines rewritten as every tools/*.sh the hand-written lines do not list
PATHS_GEN = """#!/usr/bin/env python3
import glob
lines = open(".github/convergence-paths.txt").read().splitlines(True)
b = next(i for i, x in enumerate(lines) if x.startswith("# BEGIN GENERATED"))
e = next(i for i in range(b, len(lines)) if lines[i].startswith("# END GENERATED"))
hand = lines[:b] + lines[e + 1:]
listed = {x.strip() for x in hand}
block = [p + "\\n" for p in sorted(glob.glob("tools/*.sh")) if p not in listed]
with open(".github/convergence-paths.txt", "w") as f:
    f.write("".join(hand[:b]) + "# BEGIN GENERATED\\n" + "".join(block) + "# END GENERATED\\n" + "".join(hand[b:]))
"""
CLASSES = "scripts/tool-catalogue/migration-classes.tsv"  # a hand-written table: one row a tool, keyed by its path

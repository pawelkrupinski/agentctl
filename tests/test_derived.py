    def lane(self, name, tools, paths_text=None, rows=(), alone=False, classes=()):
        """A migration lane's change: its tools written and docs/tools.md (and the path list) regenerated by the
        repo's own generator in its worktree, as the lane's author does before committing; `rows` appended to the
        lint registry (a hand-written table, no registered file); alone: landed with --no-batch."""
        wt = self.r.worktree(f"wt-{name}", branch=name)
        for path, purpose in tools.items():
            self.r.write(path, tool(purpose), at=wt)
        if paths_text is not None:
            self.r.write(PATHS, paths_text, at=wt)
        if rows:
            with open(os.path.join(wt, LINT_REGISTRY)) as f:
                self.r.write(LINT_REGISTRY, f.read() + "".join(f"{r}\n" for r in rows), at=wt)
        if classes:
            with open(os.path.join(wt, CLASSES)) as f:
                self.r.write(CLASSES, f.read() + "".join(f"{r}\n" for r in classes), at=wt)
        sh(wt, "scripts/catalogue")
        sh(wt, "scripts/paths")
        self.r.commit(f"{name}: its tools, the catalogue regenerated", at=wt)
        if alone:
            rc, out = self.land(wt, "--no-batch")
            self.assertEqual(rc, 0, out)
            return out.split("QUEUED ", 1)[1].split()[0]
        return self.queued(wt)[0]

    def in_flight(self, eid):
        """The change's check under way (its executor taken: checking)."""
        A.tick_changes(self.r.path, self.d, *on_clock(A.Clock()))
        self.assertEqual(self.started, [eid])
        A.set_change(A.CurrentStore(A.process_store), self.d, self.entry(eid), "checking", cause="agent")

    def hold_of(self, eid):
        return (A.process_store().item("change", eid)["data"] or {}).get("hold") or {}

    def regen_on_this_host(self):
        saved = A.regen_here
        A.regen_here = lambda: True  # the laptop's sync role: regen commands run
        self.addCleanup(setattr, A, "regen_here", saved)

    def on_main(self, path):
        return sh(self.r.root, "git", "--git-dir", self.r.bare, "show", f"main:{path}") + "\n"

    def generated_over_main(self, path, gen):
        """What the repo's generator writes over main's tree as it stands."""
        with tempfile.TemporaryDirectory() as td:
            sh(td, "git", "clone", "-q", self.r.bare, "c")
            sh(os.path.join(td, "c"), gen)
            with open(os.path.join(td, "c", path)) as f:
                return f.read()

    def landed(self, *ids):
        return [self.entry(x)["status"] for x in ids] == ["landed"] * len(ids)

    def test_two_lanes_regenerating_the_catalogue_combine_and_land_the_generators_page(self):
        """The 2026-11-23 replay: two lanes each add a tool next to the other's and regenerate docs/tools.md -- git
        conflicts on the rows, and the count heading is a line neither side wrote. Both land in one check, and main's
        page is exactly what the generator writes over the merged tree."""

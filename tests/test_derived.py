        base = "a\n# BEGIN GENERATED\n# END GENERATED\n"
        self.assertIsNone(A.block_merge(base, "a\n# BEGIN GENERATED\n", base, self.BLOCK))
        self.assertIsNone(A.block_merge(base, base.replace("a", "o"), base.replace("a", "t"), self.BLOCK))



"""A DERIVED FILE IS THE COMBINED TREE'S (generated.py; 2026-11-23: three parallel shell-to-Python migration lanes in
movies each regenerating docs/tools.md -- `python3 scripts/tool_catalogue.py`, from every tool's purpose line -- and
every queued one conflicting with the others there, one lane refused four times for it alone). A file registered with
`merge: derived` is regenerated over the combined tree whenever both sides changed it -- a conflict, or a clean line
merge of two edits that leaves it stale -- and its output needs no explaining by the sides (a section's count is a line
neither had); a `block` file keeps its hand-written lines, merged three-way around the generated block."""
import json, os, sys, tempfile, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from test_agentctl import A, sh  # noqa: E402
import test_backlog_batch, test_generated  # noqa: E402

CATALOGUE = "docs/tools.md"
PATHS = ".github/convergence-paths.txt"
# the repo's catalogue generator (as scripts/tool_catalogue.py): a page from every tools/*.sh `# Purpose:` line, under
# a heading that counts them -- an aggregate line two sides adding a tool each never wrote
CATALOGUE_GEN = """#!/usr/bin/env python3
import glob, re
rows = []
for p in sorted(glob.glob("tools/*.sh")):
    purpose = next((m.group(1) for m in map(re.compile(r"# Purpose: (.*)").match, open(p)) if m), "-")
    rows.append(f"| `{p}` | {purpose} |\\n")
with open("docs/tools.md", "w") as f:
    f.write(f"# Tools\\n\\nGENERATED by scripts/catalogue.\\n\\n## Tools ({len(rows)})\\n\\n| Tool | Purpose |\\n"
            + "".join(rows))
with open("{log}", "a") as f:
    f.write("ran\\n")
"""
# the repo's path-closure generator (as scripts/ci/convergence_paths.py --write): the hand-written lines kept, the
# block between its BEGIN and END lines rewritten as every tools/*.sh the hand-written lines do not list
PATHS_GEN = """#!/usr/bin/env python3
import glob
lines = open(".github/convergence-paths.txt").read().splitlines(True)
b = next(i for i, x in enumerate(lines) if x.startswith("# BEGIN GENERATED"))
e = next(i for i in range(b, len(lines)) if lines[i].startswith("# END GENERATED"))
hand = lines[:b] + lines[e + 1:]
listed = {x.strip() for x in hand}
block = [p + "\\n" for p in sorted(glob.glob("tools/*.sh")) if p not in listed]
with open(".github/convergence-paths.txt", "w") as f:
    f.write("".join(hand[:b]) + "# BEGIN GENERATED\\n" + "".join(block) + "# END GENERATED\\n" + "".join(hand[b:]))
"""
LINT_REGISTRY = "scripts/hooks/lint-registry.tsv"  # hand-written, registered nowhere: lanes append rows to its end
HAND_TOP = "# the paths a leg reads\n# by hand:\nsrc/top.txt\n"
HAND_BOTTOM = "# after the block\nsrc/bottom.txt\n"


def tool(purpose):
    return f"#!/bin/sh\n# Purpose: {purpose}\n"


class DerivedTest(test_generated.GeneratedQueueTest):
    def setUp(self):
        super().setUp()
        self.r.write("scripts/catalogue", CATALOGUE_GEN.replace("{log}", self.regen_log))
        self.r.write("scripts/paths", PATHS_GEN)
        for s in ("scripts/catalogue", "scripts/paths"):
            os.chmod(os.path.join(self.r.path, s), 0o755)
        self.r.write("tools/m.sh", tool("the middle tool"))
        self.r.write(CATALOGUE, "")
        self.r.write(LINT_REGISTRY, "# spec\treads\nweb:lint.A\tweb/*\n")
        self.r.write(PATHS, HAND_TOP + "# BEGIN GENERATED\n# END GENERATED\n" + HAND_BOTTOM)
        sh(self.r.path, "scripts/catalogue")
        sh(self.r.path, "scripts/paths")
        os.remove(self.regen_log)
        self.r.commit("the tools, their catalogue and the path list, with their generators")
        self.r.push()
        with open(os.environ["AGENTCTL_RED_REPOS"], "w") as f:
            json.dump({"repos": [{"repo": A.slug(self.r.path), "gate": [["Main", "main.yml"]], "generated": [
                {"paths": [test_generated.BASELINE], "regen": "scripts/regen"},
                {"paths": [CATALOGUE], "regen": "scripts/catalogue", "merge": "derived"},
                {"paths": [PATHS], "regen": "scripts/paths", "merge": "derived",
                 "block": ["# BEGIN GENERATED", "# END GENERATED"]}]}]}, f)
        for c in A.PROCESS_CACHES:
            c.clear()

    def lane(self, name, tools, paths_text=None, rows=(), alone=False):
        """A migration lane's change: its tools written and docs/tools.md (and the path list) regenerated by the
        repo's own generator in its worktree, as the lane's author does before committing; `rows` appended to the
        lint registry (a hand-written table, no registered file); alone: landed with --no-batch."""
        wt = self.r.worktree(f"wt-{name}", branch=name)
        for path, purpose in tools.items():
            self.r.write(path, tool(purpose), at=wt)
        if paths_text is not None:
            self.r.write(PATHS, paths_text, at=wt)
        if rows:
            with open(os.path.join(wt, LINT_REGISTRY)) as f:
                self.r.write(LINT_REGISTRY, f.read() + "".join(f"{r}\n" for r in rows), at=wt)
        sh(wt, "scripts/catalogue")
        sh(wt, "scripts/paths")
        self.r.commit(f"{name}: its tools, the catalogue regenerated", at=wt)
        if alone:
            rc, out = self.land(wt, "--no-batch")
            self.assertEqual(rc, 0, out)
            return out.split("QUEUED ", 1)[1].split()[0]
        return self.queued(wt)[0]

    def in_flight(self, eid):
        """The change's check under way (its executor taken: checking)."""
        A.tick_changes(self.r.path, self.d)
        self.assertEqual(self.started, [eid])
        A.set_change(self.d, self.entry(eid), "checking")

    def hold_of(self, eid):
        return (A.open_store().item("change", eid)["data"] or {}).get("hold") or {}

    def regen_on_this_host(self):
        saved = A.regen_here
        A.regen_here = lambda: True  # the laptop's sync role: regen commands run
        self.addCleanup(setattr, A, "regen_here", saved)

    def on_main(self, path):
        return sh(self.r.root, "git", "--git-dir", self.r.bare, "show", f"main:{path}") + "\n"

    def generated_over_main(self, path, gen):
        """What the repo's generator writes over main's tree as it stands."""
        with tempfile.TemporaryDirectory() as td:
            sh(td, "git", "clone", "-q", self.r.bare, "c")
            sh(os.path.join(td, "c"), gen)
            with open(os.path.join(td, "c", path)) as f:
                return f.read()

    def landed(self, *ids):
        return [self.entry(x)["status"] for x in ids] == ["landed"] * len(ids)

    def test_two_lanes_regenerating_the_catalogue_combine_and_land_the_generators_page(self):
        """The 2026-11-23 replay: two lanes each add a tool next to the other's and regenerate docs/tools.md -- git
        conflicts on the rows, and the count heading is a line neither side wrote. Both land in one check, and main's
        page is exactly what the generator writes over the merged tree."""
        ea = self.lane("tool-a", {"tools/a.sh": "the first tool"})
        eb = self.lane("tool-b", {"tools/b.sh": "the second tool"})
        self.assertTrue(A.pair_conflict(self.r.path, self.entry(ea), self.entry(eb)), "git conflicts here")
        A.tick_changes(self.r.path, self.d)
        self.assertEqual(self.started, [], "both wait for the backlog batch, neither held behind the other")
        self.drive_as("sync")
        self.assertTrue(self.landed(ea, eb), [self.entry(x) for x in (ea, eb)])
        self.assertEqual(len(self.calls_of("--range")), 1, "one tree, one check")
        page = self.on_main(CATALOGUE)
        self.assertIn("## Tools (3)", page, "the combined count, which neither side had")
        self.assertEqual(page, self.generated_over_main(CATALOGUE, "scripts/catalogue"))
        self.assertEqual(self.on_main(PATHS), self.generated_over_main(PATHS, "scripts/paths"))

    def test_a_clean_line_merge_that_leaves_the_catalogue_stale_is_regenerated(self):
        """Rows apart and the same new count on both sides: git merges the page cleanly -- one tool short in its
        count. Regenerated all the same over the combined tree."""
        ea = self.lane("tool-a", {"tools/a.sh": "the first tool"})
        ez = self.lane("tool-z", {"tools/z.sh": "the last tool"})
        A.tick_changes(self.r.path, self.d)
        self.drive_as("sync")
        self.assertTrue(self.landed(ea, ez), [self.entry(x) for x in (ea, ez)])
        self.assertIn("## Tools (3)", self.on_main(CATALOGUE))
        self.assertEqual(self.on_main(CATALOGUE), self.generated_over_main(CATALOGUE, "scripts/catalogue"))

    def test_a_block_files_hand_written_lines_are_merged_and_its_block_regenerated(self):
        """convergence-paths.txt: each lane edits its own hand-written line (one above the block, one below) and adds
        a tool to the generated block, beside the other's. Both hand edits are kept, the block is the generator's."""
        main_paths = self.on_main(PATHS)  # the older adds the later tool: a union of the two blocks is out of order
        ea = self.lane("paths-a", {"tools/b.sh": "b"}, main_paths.replace("src/top.txt", "src/top-a.txt"))
        eb = self.lane("paths-b", {"tools/a.sh": "a"}, main_paths.replace("src/bottom.txt", "src/bottom-b.txt"))
        A.tick_changes(self.r.path, self.d)
        self.drive_as("sync")
        self.assertTrue(self.landed(ea, eb), [self.entry(x) for x in (ea, eb)])
        paths = self.on_main(PATHS)
        self.assertIn("src/top-a.txt\n", paths)
        self.assertIn("src/bottom-b.txt\n", paths)
        self.assertIn("# BEGIN GENERATED\ntools/a.sh\ntools/b.sh\ntools/m.sh\n# END GENERATED\n", paths)
        self.assertEqual(paths, self.generated_over_main(PATHS, "scripts/paths"))

    def test_a_hand_written_line_both_lanes_changed_is_no_resolution(self):
        main_paths = self.on_main(PATHS)
        ea = self.lane("paths-a", {"tools/a.sh": "a"}, main_paths.replace("src/top.txt", "src/top-a.txt"))
        eb = self.lane("paths-b", {"tools/b.sh": "b"}, main_paths.replace("src/top.txt", "src/top-b.txt"))
        A.tick_changes(self.r.path, self.d)
        self.drive_as("sync")
        self.assertEqual(self.entry(eb)["batch_alone"], "regen")
        self.assertIn(f"{PATHS}: both sides changed its hand-written lines",
                      open(os.path.join(self.d, "processor.log")).read())
        self.assertNotEqual(self.entry(eb)["status"], "landed", "the author's conflict")

    # ----------------------------------------------------------------------------------- A DERIVED FILE HOLDS NOTHING
    def test_two_lanes_adding_catalogue_tools_and_lint_rows_are_checked_as_one_and_combine(self):
        """The 2026-11-23 migration lanes: each adds a tool (docs/tools.md regenerated) and appends a row to the
        hand-written lint registry at its end -- git conflicts in both. Neither holds the other: one backlog batch, the
        catalogue regenerated and the registry's additions both kept (THE BATCH TIERS, tier 3)."""
        self.regen_on_this_host()
        ea = self.lane("tool-a", {"tools/a.sh": "the first tool"}, rows=["web:lint.B\tweb/b/*"])
        eb = self.lane("tool-b", {"tools/b.sh": "the second tool"}, rows=["worker:lint.C\tworker/*"])
        A.tick_changes(self.r.path, self.d)
        self.assertEqual(self.started, [], "both wait for the backlog batch")
        self.assertNotIn(self.hold_of(eb).get("kind"), ("overlap",), "never held behind the other")
        self.drive_as("sync")
        self.assertTrue(self.landed(ea, eb), [self.entry(x) for x in (ea, eb)])
        self.assertEqual(len(self.calls_of("--range")), 1, "one tree, one check")
        self.assertEqual(self.on_main(CATALOGUE), self.generated_over_main(CATALOGUE, "scripts/catalogue"))
        self.assertTrue(self.on_main(LINT_REGISTRY).endswith("web:lint.B\tweb/b/*\nworker:lint.C\tworker/*\n"))

    def test_a_lane_sharing_only_the_catalogue_with_a_check_in_flight_is_checked_now(self):
        """A DERIVED FILE HOLDS NOTHING: before, the younger lane sat `its check waits for <older> (checking): both
        change docs/tools.md` -- three lanes landed one after another. Now it is checked at once, beside the older; at
        its push the catalogue both changed is regenerated over the combined tree in a new round, and main's page is
        the generator's."""
        self.regen_on_this_host()
        ea = self.lane("tool-a", {"tools/a.sh": "the first tool"}, alone=True)
        self.in_flight(ea)
        eb = self.lane("tool-b", {"tools/b.sh": "the second tool"})
        A.tick_changes(self.r.path, self.d)
        self.assertIn(eb, self.started, f"checked now, beside the older: {self.hold_of(eb)}")
        self.assertNotEqual(self.hold_of(eb).get("kind"), "overlap")
        self.check_and_push(ea, eb)

    def test_a_clean_line_merge_of_the_catalogue_at_the_push_is_a_new_round_never_a_stale_page(self):
        """Rows apart (a.sh, z.sh): main's page and the younger's merge cleanly at its push -- one tool short in the
        count. The push owes the regenerated page: a new round, never git's clean merge pushed."""
        self.regen_on_this_host()
        ea = self.lane("tool-a", {"tools/a.sh": "the first tool"}, alone=True)
        self.in_flight(ea)
        ez = self.lane("tool-z", {"tools/z.sh": "the last tool"})
        A.tick_changes(self.r.path, self.d)
        self.assertIn(ez, self.started, f"checked now: {self.hold_of(ez)}")
        self.check_and_push(ea, ez)
        self.assertIn(f"main moved under regenerated files it changes too (.github/convergence-paths.txt, {CATALOGUE})",
                      open(os.path.join(self.d, "processor.log")).read(), "the new round is owed for the page")

    def check_and_push(self, older, younger):
        A.check_entry(self.r.path, older, self.clock)
        A.check_entry(self.r.path, younger, self.clock)  # checked on the main the older has not reached yet
        A.tick_changes(self.r.path, self.d)  # pushes the older; the younger's push finds main moved
        for _ in range(4):
            if self.entry(younger)["status"] == "queued":
                A.check_entry(self.r.path, younger, self.clock)  # its new round, on main with the older
            A.tick_changes(self.r.path, self.d)
            if self.entry(younger)["status"] in A.ENTRY_FINAL:
                break
        self.assertTrue(self.landed(older, younger), [self.entry(x) for x in (older, younger)])
        self.assertIn("## Tools (3)", self.on_main(CATALOGUE), "the combined count")
        self.assertEqual(self.on_main(CATALOGUE), self.generated_over_main(CATALOGUE, "scripts/catalogue"))

    def test_a_lint_row_shared_with_a_check_in_flight_still_holds(self):
        """The additive tier resolves a hand-written file only in a backlog batch's assembly, whose full check is the
        verification. With the older already in flight there is no batch to meet in: checked now, the younger's push
        finds the registry both changed -- THE RULE's full round (`both touch ...`; the lint registry selects checks)
        or, conflicting, no resolution at the push's rebase -- so a check now is one thrown away. It waits, as before."""
        ea = self.lane("tool-a", {"tools/a.sh": "a"}, rows=["web:lint.B\tweb/b/*"], alone=True)
        self.in_flight(ea)
        eb = self.lane("tool-b", {"tools/b.sh": "b"}, rows=["worker:lint.C\tworker/*"])
        A.tick_changes(self.r.path, self.d)
        self.assertNotIn(eb, self.started, "the younger waits for the check in flight")
        self.assertEqual((self.hold_of(eb).get("blocker"), self.hold_of(eb).get("files")), (ea, [LINT_REGISTRY]),
                         "held for the lint registry, never the catalogue")


class BlockMergeTest(unittest.TestCase):
    BLOCK = ["# BEGIN GENERATED", "# END GENERATED"]

    def test_the_hand_written_lines_merge_and_ours_block_stands_for_the_regen(self):
        base = "a\nb\n# BEGIN GENERATED\nx\n# END GENERATED\nc\n"
        ours = "A\nb\n# BEGIN GENERATED\nx\ny\n# END GENERATED\nc\n"
        theirs = "a\nb\n# BEGIN GENERATED\nw\nx\n# END GENERATED\nC\n"
        self.assertEqual(A.block_merge(base, ours, theirs, self.BLOCK),
                         "A\nb\n# BEGIN GENERATED\nx\ny\n# END GENERATED\nC\n")

    def test_a_side_without_a_whole_block_or_a_hand_conflict_is_no_merge(self):
        base = "a\n# BEGIN GENERATED\n# END GENERATED\n"
        self.assertIsNone(A.block_merge(base, "a\n# BEGIN GENERATED\n", base, self.BLOCK))
        self.assertIsNone(A.block_merge(base, base.replace("a", "o"), base.replace("a", "t"), self.BLOCK))


class DerivedRegistryTest(unittest.TestCase):
    def parse(self, g):
        conf = A.red_repos_parse({"repos": [{"repo": "o/r", "gate": [["Main", "main.yml"]], "generated": [g]}]})
        return next(c for c in conf if c["repo"] == "o/r")["generated"][0]

    def test_a_derived_entry_and_its_block_parse_and_a_bad_one_is_refused(self):
        got = self.parse({"paths": [PATHS], "regen": "scripts/paths", "merge": "derived", "block": ["# B", "# E"]})
        self.assertEqual((got["merge"], got["block"]), ("derived", ["# B", "# E"]))
        self.assertTrue(A.regen_only(got))
        self.assertFalse(A.explained(got), "a derived file's output needs no explaining")
        self.assertTrue(A.explained(self.parse({"paths": [PATHS], "regen": "x", "merge": "regen"})))
        for bad in ({"paths": [PATHS], "merge": "derived"},
                    {"paths": [PATHS], "regen": "x", "block": ["# B", "# E"]},
                    {"paths": [PATHS], "regen": "x", "merge": "derived", "block": ["# B"]}):
            with self.assertRaises(ValueError, msg=bad):
                self.parse(bad)



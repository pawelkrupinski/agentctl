# agentctl, part `config`: the knobs, read from the code; `agentctl config`.
# A real module (lib/agentctl/__init__.py MODULES): its own imports, the standard library's and MODULES' only.

import ast
import json
import operator
import os
import re
from typing import Any, Callable
from agentctl.statefile import note_failure
from agentctl.selfcode import TOOL_PATH, code_files
from agentctl.configfile import CONFIG_ERRORS, CONFIG_SOURCE, config_files
from agentctl.core import HOME
from agentctl.paths import tilde


# ---------------------------------------------------------------- config: every knob, generated from the code
# The knobs are what the code reads: each `env_num("AGENTCTL_X", DEFAULT)` and `os.environ.get("AGENTCTL_X", DEFAULT)`
# (config_knobs scans the code, so a new knob is listed the moment it is read). Its default is the code's (a constant
# evaluated from the source: config_constants), its doc the comment on that constant's line, else on the line that
# reads it. Names in CONFIG_INTERNAL are not knobs: a process's identity, secrets, and test hooks -- never set in a config file. The
# file is read by core's config_load; `agentctl config` shows what applies, `config defaults` prints a complete file,
# `config doc --write` regenerates AGENTCTL.md's reference (a test keeps the two in step).
CONFIG_INTERNAL = {
    "AGENT_NAME", "CLAIM_PID", "FIXER_RECORD", "LEASE_SECRET", "LEASE_SECRETS", "RED_FIXER", "INTERACTIVE", "NOW",
    "STORE_TOKEN", "CONFIG", "CONFIG_SET", "UNDER_TEST", "TEST_RUN_TMP", "TEST_RUN_SOCK", "TEST_TIMEOUT", "TEST_JOBS",
    "TEST_VERBOSE", "JVM_PS", "JVM_CWD", "JVM_KEPT",
    "LAUNCHCTL", "OPEN", "STORE_DEFAULT_URL", "WAITING_DIR_UNUSED", "ROLE", "HOST", "LAPTOP_PRESSURE", "NO_SECRETS", "DETACHED",
}
CONFIG_DOC_BEGIN = "<!-- agentctl config doc: generated by `agentctl config doc --write`; do not edit by hand -->"
CONFIG_DOC_END = "<!-- end of the generated config reference -->"


def config_source_text():
    """All of agentctl's code (the entry and its parts), one text per file: (relative path, text)."""
    out = []
    for rel, p in code_files(TOOL_PATH):
        try:
            with open(p) as f:
                out.append((rel, f.read()))
        except FileNotFoundError:
            pass
        except OSError as e:
            note_failure("source unreadable", e)
    return out


CONSTANT_OPS: dict[str, Callable[[Any, Any], Any]] = {"Add": operator.add, "Sub": operator.sub, "Mult": operator.mul, "FloorDiv": operator.floordiv,
                "Div": operator.truediv, "LShift": operator.lshift}


def assigned_pairs(node: ast.stmt) -> list[tuple[ast.expr, ast.expr]]:
    """(target, value) of a top-level assignment, a tuple one (`A, B = 1, 2`) pair by pair; [] for any other stmt."""
    if not (isinstance(node, ast.Assign) and len(node.targets) == 1):
        return []
    target, value = node.targets[0], node.value
    if isinstance(target, ast.Tuple) and isinstance(value, ast.Tuple) and len(target.elts) == len(value.elts):
        return list(zip(target.elts, value.elts))
    return [(target, value)]


def constant_exprs(texts: list[tuple[str, str]]) -> dict[str, ast.expr]:
    """NAME -> the expression its first top-level assignment in the code gives it."""
    exprs: dict[str, ast.expr] = {}
    for _rel, text in texts:
        for node in ast.parse(text).body:
            for target, value in assigned_pairs(node):
                if isinstance(target, ast.Name):
                    exprs.setdefault(target.id, value)
    return exprs


class ConstantReader:
    """The value of a constant expression of the code: a literal, HOME, another constant, -x, x <op> y,
    os.path.join(...); ValueError for anything else (a call, an environment read). One reader per node kind."""

    def __init__(self, exprs: dict[str, ast.expr]):
        self.exprs = exprs

    def value(self, node: ast.expr, seen: frozenset[str]) -> Any:
        read = getattr(self, f"read_{type(node).__name__}", None)
        if read is None:
            raise ValueError(ast.unparse(node))
        return read(node, seen)

    def read_Constant(self, node: ast.Constant, seen: frozenset[str]) -> Any:
        if isinstance(node.value, (int, float, str, bool)):
            return node.value
        raise ValueError(repr(node.value))

    def read_Name(self, node: ast.Name, seen: frozenset[str]) -> Any:
        if node.id == "HOME":  # core's, the one the running code joins its paths to
            return HOME
        if node.id not in self.exprs or node.id in seen:
            raise ValueError(node.id)
        return self.value(self.exprs[node.id], seen | {node.id})

    def read_UnaryOp(self, node: ast.UnaryOp, seen: frozenset[str]) -> Any:
        if not isinstance(node.op, ast.USub):
            raise ValueError(ast.unparse(node))
        return -self.value(node.operand, seen)

    def read_BinOp(self, node: ast.BinOp, seen: frozenset[str]) -> Any:
        op = CONSTANT_OPS.get(type(node.op).__name__)
        if op is None:
            raise ValueError(ast.unparse(node))
        return op(self.value(node.left, seen), self.value(node.right, seen))

    def read_Call(self, node: ast.Call, seen: frozenset[str]) -> Any:
        if ast.unparse(node.func) != "os.path.join" or node.keywords:
            raise ValueError(ast.unparse(node))
        return os.path.join(*[self.value(a, seen) for a in node.args])


def config_constants(texts: list[tuple[str, str]]) -> dict[str, Any]:
    """NAME -> value of each top-level constant the code assigns from literals and other such constants, by + - * / //
    and << (`RED_FIX_GIVEUP = 2 * RED_FIX_DECIDE`) or os.path.join under HOME: read from the source, never from a
    running namespace, so the defaults shown are the code's whatever the environment overrides."""
    exprs, out = constant_exprs(texts), {}
    reader = ConstantReader(exprs)
    for name, node in exprs.items():
        try:
            out[name] = reader.value(node, frozenset({name}))
        except (ValueError, TypeError, ArithmeticError):
            pass
    return out


def config_default(expr: str | None, constants: dict[str, Any]) -> Any:
    """A default's value: a literal, a constant of the code (config_constants), else the expression as written."""
    if expr is None:
        return None
    e = expr.strip()
    try:
        return ast.literal_eval(e)
    except (ValueError, SyntaxError):
        pass
    return constants.get(e, e) if re.fullmatch(r"[A-Z_][A-Z0-9_]*", e) else e


KNOB_READ = re.compile(r'(?:env_num|env_text|os\.environ\.get)\(\s*"AGENTCTL_([A-Z0-9_]+)"\s*(?:,\s*([^)\n]+?))?\s*\)')
CONSTANT_NAME = re.compile(r"[A-Z_][A-Z0-9_]*")


def _constant_docs(texts: list[tuple[str, str]]) -> dict[str, str]:
    """NAME -> the comment on the line of each top-level constant's assignment (the first one found)."""
    docs: dict[str, str] = {}
    for _rel, text in texts:
        for m in re.finditer(r"^([A-Z_][A-Z0-9_]*) = [^\n#]*#\s*(.+)$", text, re.M):
            docs.setdefault(m.group(1), m.group(2).strip())
    return docs


def _knob_doc(docs: dict[str, str], expr: str | None, line: str) -> str | None:
    """A read's doc: the comment on its default constant's line, else the comment on the line that reads it."""
    doc = docs.get(expr.strip()) if expr and CONSTANT_NAME.fullmatch(expr.strip()) else None
    if not doc and "#" in line:
        doc = line.split("#", 1)[1].strip()
    return doc


def _note_knob_read(knobs: dict[str, dict[str, Any]], constants: dict[str, Any], docs: dict[str, str], rel: str, text: str,
                    m: re.Match[str]) -> None:
    """Adds one read of a knob (the regex match m in text of file rel) to knobs: its first default and its first doc."""
    key, expr = m.group(1), m.group(2)
    line = text[text.rfind("\n", 0, m.start()) + 1:text.find("\n", m.end())]
    doc = _knob_doc(docs, expr, line)
    k = knobs.setdefault(key, {"name": f"AGENTCTL_{key}", "key": key.lower(), "default": None, "doc": "", "where": rel})
    if k["default"] is None and expr is not None:
        k["default"] = config_default(expr, constants)
    if not k["doc"] and doc:
        k["doc"] = re.sub(r"\(\$AGENTCTL_[A-Z0-9_]+\)", "", doc).strip(" ;,")


def config_knobs():
    """[{name, key, default, doc, where}] of every knob the code reads, sorted by name."""
    texts = config_source_text()
    constants = config_constants(texts)
    docs = _constant_docs(texts)
    knobs: dict[str, dict[str, Any]] = {}
    for rel, text in texts:
        for m in KNOB_READ.finditer(text):
            if m.group(1) not in CONFIG_INTERNAL:
                _note_knob_read(knobs, constants, docs, rel, text, m)
    return sorted(knobs.values(), key=lambda k: k["name"])


def config_toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(str(v))


def config_defaults_text():
    """A complete agentctl.toml: every knob, commented out at its code default, with its doc."""
    lines = ["# agentctl.toml: every knob at its code default (`agentctl config defaults`). Uncomment to change one;",
             "# an environment variable AGENTCTL_<KEY> overrides this file. Files: /etc/agentctl/agentctl.toml (the",
             "# server copy), then ~/.config/agentctl/agentctl.toml; $AGENTCTL_CONFIG names one file instead.", ""]
    for k in config_knobs():
        if k["doc"]:
            lines.append(f"# {k['doc']}")
        v = config_toml_value(k["default"]) if k["default"] is not None else '""'
        lines.append(f"# {k['key']} = {v}")
    return "\n".join(lines) + "\n"


def config_doc_text():
    """AGENTCTL.md's reference table (generated)."""
    rows = [CONFIG_DOC_BEGIN, "", "| key (`agentctl.toml`) | environment | default | what |", "|---|---|---|---|"]
    for k in config_knobs():
        d = "" if k["default"] is None else tilde(str(k["default"]))  # the same text on every machine
        rows.append(f"| `{k['key']}` | `{k['name']}` | {('`' + d + '`') if d else '-'} | "
                    f"{k['doc'].replace('|', '/') or '-'} |")
    return "\n".join(rows + ["", CONFIG_DOC_END])


def config_doc_write(path=None):
    path = path or os.path.join(os.path.dirname(TOOL_PATH), "AGENTCTL.md")
    with open(path) as f:
        text = f.read()
    if CONFIG_DOC_BEGIN not in text:
        raise SystemExit(f"agentctl: {path} has no generated config section ({CONFIG_DOC_BEGIN})")
    head, rest = text.split(CONFIG_DOC_BEGIN, 1)
    tail = rest.split(CONFIG_DOC_END, 1)[1]
    new = head + config_doc_text() + tail
    if new != text:
        with open(path, "w") as f:
            f.write(new)
    return new != text


def _config_defaults(a: Any) -> int:
    print(config_defaults_text(), end="")
    return 0


def _config_doc(a: Any) -> int:
    if a.write:
        print("AGENTCTL.md: the config reference " + ("regenerated" if config_doc_write() else "is current"))
    else:
        print(config_doc_text())
    return 0


def _config_files_line() -> str:
    return "files: " + (", ".join(f"{p}{'' if os.path.exists(p) else ' (none)'}" for p in config_files()) or "none")


def _knob_line(k: dict[str, Any], every: bool) -> str | None:
    """A knob's line (its value and where that comes from) when it is set in the environment (every: or not)."""
    v = os.environ.get(k["name"])
    if not (every or v is not None):
        return None
    src = CONFIG_SOURCE.get(k["name"]) or ("environment" if v is not None else "default")
    return f"  {k['key']:<28} = {v if v is not None else k['default']}  ({src})"


def _config_show(a: Any) -> int:
    """The files read, their unreadable ones, and each knob set (every knob with --all) with where its value comes from."""
    print(_config_files_line())
    for e in CONFIG_ERRORS:
        print(f"  UNREADABLE {e}")
    for k in config_knobs():
        line = _knob_line(k, a.all)
        if line is not None:
            print(line)
    return 0


def cmd_config(a):
    return {"defaults": _config_defaults, "doc": _config_doc}.get(a.ccmd, _config_show)(a)

def config_defaults_text():
    """A complete agentctl.toml: every knob, commented out at its code default, with its doc."""
    lines = ["# agentctl.toml: every knob at its code default (`agentctl config defaults`). Uncomment to change one;",
             "# an environment variable AGENTCTL_<KEY> overrides this file. Files: /etc/agentctl/agentctl.toml (the",
             "# server copy), then ~/.config/agentctl/agentctl.toml; $AGENTCTL_CONFIG names one file instead.", ""]
    for k in config_knobs():
        if k["doc"]:
            lines.append(f"# {k['doc']}")
        v = config_toml_value(k["default"]) if k["default"] is not None else '""'
        lines.append(f"# {k['key']} = {v}")
    return "\n".join(lines) + "\n"


def config_doc_text():
    """AGENTCTL.md's reference table (generated)."""
    rows = [CONFIG_DOC_BEGIN, "", "| key (`agentctl.toml`) | environment | default | what |", "|---|---|---|---|"]
    for k in config_knobs():
        d = "" if k["default"] is None else str(k["default"]).replace(HOME, "~")  # the same text on every machine
        rows.append(f"| `{k['key']}` | `{k['name']}` | {('`' + d + '`') if d else '-'} | "
                    f"{k['doc'].replace('|', '/') or '-'} |")
    return "\n".join(rows + ["", CONFIG_DOC_END])


def config_doc_write(path=None):
    path = path or os.path.join(os.path.dirname(TOOL_PATH), "AGENTCTL.md")
    with open(path) as f:
        text = f.read()
    if CONFIG_DOC_BEGIN not in text:
        raise SystemExit(f"agentctl: {path} has no generated config section ({CONFIG_DOC_BEGIN})")
    head, rest = text.split(CONFIG_DOC_BEGIN, 1)
    tail = rest.split(CONFIG_DOC_END, 1)[1]
    new = head + config_doc_text() + tail
    if new != text:
        with open(path, "w") as f:
            f.write(new)
    return new != text


